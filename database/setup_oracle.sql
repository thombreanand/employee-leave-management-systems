CREATE TABLE LEAVE_REQUESTS (
  ID VARCHAR2(80) PRIMARY KEY,
  EMPLOYEE_ID VARCHAR2(80) NOT NULL,
  EMPLOYEE_NAME VARCHAR2(150) NOT NULL,
  EMPLOYEE_EMAIL VARCHAR2(254) NOT NULL,
  LEAVE_TYPE VARCHAR2(40) NOT NULL,
  FROM_DATE DATE NOT NULL,
  TO_DATE DATE NOT NULL,
  DAYS NUMBER(5) NOT NULL,
  REASON VARCHAR2(2000) NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'Pending' NOT NULL
    CONSTRAINT CK_LEAVE_STATUS CHECK (STATUS IN ('Pending','Approved','Rejected')),
  MANAGER_COMMENT VARCHAR2(2000),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_LEAVE_DATES CHECK (TO_DATE >= FROM_DATE)
);
CREATE INDEX IDX_LEAVE_STATUS ON LEAVE_REQUESTS(STATUS);
CREATE INDEX IDX_LEAVE_EMPLOYEE ON LEAVE_REQUESTS(EMPLOYEE_ID);

